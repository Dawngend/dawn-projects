def build_word_pattern(words):
    pattern = "|".join(re.escape(word) for word in words)
    return re.compile(r"\b(" + pattern + r")\b", re.IGNORECASE)


TITLE_PATTERN = build_word_pattern(TITLE_KEYWORDS)
CLOSED_LOCATION_PATTERN = build_word_pattern(CLOSED_LOCATIONS)


def title_matches(title):
    return TITLE_PATTERN.search(title or "") is not None


def location_is_open(location):
    # A location that names no country counts as open, including a blank one.
    return CLOSED_LOCATION_PATTERN.search(location or "") is None


def is_eligible(posting):
    return title_matches(posting["title"]) and location_is_open(posting["location"])
